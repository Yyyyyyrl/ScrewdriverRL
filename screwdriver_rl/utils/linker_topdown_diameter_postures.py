def bucket_for_diameter_mm(diameter_mm: int) -> int:
    diameter_m = float(diameter_mm) / 1000.0
    try:
        return TOPDOWN_HANDLE_DIAMETERS_M.index(diameter_m)
    except ValueError as exc:
        supported = [round(value * 1000) for value in TOPDOWN_HANDLE_DIAMETERS_M]
        raise ValueError(
            f"unsupported top-down diameter {diameter_mm} mm; expected one of {supported}"
        ) from exc
